from nltk.tokenize import sent_tokenize, word_tokenize, wordpunct_tokenize,TreebankWordTokenizer # type: ignore

corpus='Cricket is a popular bat-and-ball sport. It is played between two teams of eleven players. The game takes place on an oval field with a central rectangular pitch. Cricket originated in England and is now a global phenomenon. It is hugely popular in countries like India, Australia, and the United Kingdom. Matches are played in different formats, including five-day Test matches. Shorter formats include One Day Internationals and Twenty20 games. Teams take turns batting to score runs. The other team bowls and fields to get batters out and limit runs. Cricket teaches teamwork, patience, and sportsmanship. It unites millions of passionate fans around the world.'


# Tokens as Sentences
print('\nTokens as Sentences: \n')
documents=sent_tokenize(corpus)
print(documents)

# Tokens as Words
print('\nTokens as Words: \n')
words=word_tokenize(corpus)
print(words)

# Tokens as Words Even Punctuation
print('\nTokens as Words Even Punctuation: \n')
words_punct=wordpunct_tokenize(corpus)
print(words_punct)

# Comparing tokens generated by word_tokenize and wordpunct_tokenize

print('\nTokens present in wordpunct_tokenize but not in word_tokenize:\n')
print([word for word in words_punct if word not in words])

print('\nTokens present in word_tokenize but not in wordpunct_tokenize:\n')
print([word for word in words if word not in words_punct])


# Tokens as last word with dot.
treeBankwords=TreebankWordTokenizer().tokenize(corpus)
print('\nTokens as last word with dot: \n')
print(treeBankwords)